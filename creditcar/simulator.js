export function calcularCuotasCreditcar(montoSolicitado, categoria) {
  const monto = Number(montoSolicitado);
  const plan = planesCreditcar[categoria];

  if (!Number.isFinite(monto) || monto <= 0) {
    throw new Error("El monto solicitado debe ser mayor que cero.");
  }

  if (!plan) {
    throw new Error("La categoría seleccionada no es válida.");
  }

  const cuotas = Object.entries(plan.indices).map(([plazo, indice]) => ({
    plazo: Number(plazo),
    indice,
    cuota: monto * indice
  }));

  return {
    montoSolicitado: monto,
    categoria,
    nombreCategoria: plan.nombre,
    ltvMaximo: plan.ltvMaximo,
    cuotas
  };
}
